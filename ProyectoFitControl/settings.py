# PostgreSQL remoto: DATABASE_URL se configura fuera del repositorio.
# Sin esa variable se mantiene MariaDB local; las pruebas pueden usar SQLite.
if os.environ.get('DATABASE_URL') and os.environ.get('FITCONTROL_SQLITE') != '1':
    from urllib.parse import urlparse, unquote

    _database_url = urlparse(os.environ['DATABASE_URL'])
    if _database_url.scheme not in ('postgres', 'postgresql'):
        raise ValueError('DATABASE_URL debe ser una conexión PostgreSQL.')
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': unquote(_database_url.path.lstrip('/')),
            'USER': unquote(_database_url.username or ''),
            'PASSWORD': unquote(_database_url.password or ''),
            'HOST': _database_url.hostname,
            'PORT': _database_url.port or 5432,
            'CONN_MAX_AGE': 0,
            'DISABLE_SERVER_SIDE_CURSORS': True,
            'OPTIONS': {
                'sslmode': 'require',
                'connect_timeout': 20,
                'prepare_threshold': None,
            },
        }
    }

